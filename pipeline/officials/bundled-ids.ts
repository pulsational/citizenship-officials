/// <reference types="node" />
// 任务 PH：app 里已经打包了照片的人（id 列表）。每日流程只给「不在这份名单里」的人找照片，打包过的一律跳过、不重复发布。
//
// bundled-photo-ids.json 怎么来的：从 app 打包的 assets/officials/photos-manifest.json 取出全部 id（只要 id，不带别的字段），
//   node pipeline/officials/bundled-ids.ts <app 仓库>/assets/officials/photos-manifest.json <app 提交 hash> > pipeline/officials/bundled-photo-ids.json
// app 换了打包的照片（加人、换届）就用同一条命令重新生成，一起提交。
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const BUNDLED_IDS_FILE = join(dirname(fileURLToPath(import.meta.url)), 'bundled-photo-ids.json');
/** id 的样子：bioguideId（A000055）或 gov-州（gov-IA） */
export const PHOTO_ID_RE = /^[A-Za-z0-9-]{1,40}$/;

export interface BundledIdsFile { _comment: string; source: string; appCommit: string; count: number; ids: string[] }

/** 打包清单 → 文件内容（id 排序、去重；清单里有不像 id 的、重复的就报错，不生成） */
export function bundledIdsFrom(manifest: { entries?: { id?: unknown }[] }, appCommit: string): BundledIdsFile {
  if (!Array.isArray(manifest.entries)) throw new Error('清单里没有 entries');
  if (!/^[0-9a-f]{7,40}$/.test(appCommit)) throw new Error(`提交 hash 不对：${appCommit}`);
  const ids = manifest.entries.map((e) => e.id);
  const bad = ids.filter((id) => typeof id !== 'string' || !PHOTO_ID_RE.test(id));
  if (bad.length) throw new Error(`清单里有不像 id 的：${bad.slice(0, 5).join(', ')}`);
  const sorted = [...(ids as string[])].sort();
  if (new Set(sorted).size !== sorted.length) throw new Error('清单里 id 有重复');
  return {
    _comment: 'Ids of officials whose photo is already bundled in the app. The daily photo step skips them. Generated by pipeline/officials/bundled-ids.ts from the app\'s assets/officials/photos-manifest.json at appCommit.',
    source: 'assets/officials/photos-manifest.json', appCommit, count: sorted.length, ids: sorted,
  };
}

/** 读这份文件，严格检查（count 对得上、id 合法、不重复）；不对就抛异常，整次运行失败——宁可停，也不要把 582 张全重新下一遍 */
export function loadBundledIds(path = BUNDLED_IDS_FILE): Set<string> {
  const f = JSON.parse(readFileSync(path, 'utf8')) as Partial<BundledIdsFile>;
  if (!Array.isArray(f.ids) || f.ids.some((id) => typeof id !== 'string' || !PHOTO_ID_RE.test(id))) throw new Error(`${path}：ids 不对`);
  const s = new Set(f.ids);
  if (s.size !== f.ids.length || f.count !== s.size) throw new Error(`${path}：ids 有重复或 count 对不上`);
  return s;
}

function main() {
  const [manifestPath, appCommit] = process.argv.slice(2);
  if (!manifestPath || !appCommit) { console.error('用法：node pipeline/officials/bundled-ids.ts <app 的 photos-manifest.json> <app 提交 hash>'); process.exit(2); }
  process.stdout.write(JSON.stringify(bundledIdsFrom(JSON.parse(readFileSync(manifestPath, 'utf8')), appCommit), null, 1) + '\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try { main(); } catch (e) { console.error(`失败：${e instanceof Error ? e.message : e}`); process.exit(2); }
}
