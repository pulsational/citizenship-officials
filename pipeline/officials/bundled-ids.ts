/// <reference types="node" />
// 任务 PH：app 里已经打包了照片的人（id + 名字）。每日流程只给「不在这份名单里」的人找照片：
// id 和名字都一样才算打包过、跳过；同一个 id 换了人（州长 gov-CA 换届、id 不变）名字就不一样 → 不算打包过，照常给新的人找照片。
//
// bundled-photo-ids.json 怎么来的：从 app 打包的 assets/officials/photos-manifest.json 取出每条的 id 和 name（不带别的字段），
//   node pipeline/officials/bundled-ids.ts <app 仓库>/assets/officials/photos-manifest.json <app 提交 hash> > pipeline/officials/bundled-photo-ids.json
// 只在 app 换了打包的照片时（发版时）手动重新生成、一起提交；平时不动。
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const BUNDLED_IDS_FILE = join(dirname(fileURLToPath(import.meta.url)), 'bundled-photo-ids.json');
/** id 的样子：bioguideId（A000055）或 gov-州（gov-IA） */
export const PHOTO_ID_RE = /^[A-Za-z0-9-]{1,40}$/;

/** 比名字用的写法：NFC、去掉首尾空白、中间连续空白并成一个空格；大小写、标点都不动（保守）。
 *  app 那边 src/photos/photos.ts 的 normalizePhotoName 是同一套，两边要一起改 */
export function normalizePhotoName(s: string): string {
  return s.normalize('NFC').trim().replace(/\s+/g, ' ');
}

/** 打包过 = 这个 id 在名单里，而且名字（按上面的写法）一样 */
export function isBundled(bundled: ReadonlyMap<string, string>, id: string, name: string): boolean {
  const b = bundled.get(id);
  return b !== undefined && b === normalizePhotoName(name);
}

export interface BundledIdsFile { _comment: string; source: string; appCommit: string; count: number; entries: { id: string; name: string }[] }

/** 打包清单 → 文件内容（按 id 排序；清单里有不像 id 的、重复 id、没名字的就报错，不生成） */
export function bundledIdsFrom(manifest: { entries?: { id?: unknown; name?: unknown }[] }, appCommit: string): BundledIdsFile {
  if (!Array.isArray(manifest.entries)) throw new Error('清单里没有 entries');
  if (!/^[0-9a-f]{7,40}$/.test(appCommit)) throw new Error(`提交 hash 不对：${appCommit}`);
  const bad = manifest.entries.filter((e) => typeof e.id !== 'string' || !PHOTO_ID_RE.test(e.id));
  if (bad.length) throw new Error(`清单里有不像 id 的：${bad.slice(0, 5).map((e) => String(e.id)).join(', ')}`);
  const noName = manifest.entries.filter((e) => typeof e.name !== 'string' || !e.name.trim());
  if (noName.length) throw new Error(`清单里有没名字的：${noName.slice(0, 5).map((e) => String(e.id)).join(', ')}`);
  const entries = manifest.entries.map((e) => ({ id: e.id as string, name: normalizePhotoName(e.name as string) })).sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  if (new Set(entries.map((e) => e.id)).size !== entries.length) throw new Error('清单里 id 有重复');
  return {
    _comment: 'Officials whose photo is already bundled in the app (id + name). The daily photo step skips a person only when both id and name match. Generated by pipeline/officials/bundled-ids.ts from the app\'s assets/officials/photos-manifest.json at appCommit; regenerated by hand only when the app\'s bundled photos change (app release).',
    source: 'assets/officials/photos-manifest.json', appCommit, count: entries.length, entries,
  };
}

/** 读这份文件，严格检查（count 对得上、id 合法、不重复、有名字）；不对就抛异常，整次运行失败——宁可停，也不要把几百张全重新下一遍。
 *  返回 id → 名字（已按 normalizePhotoName 处理） */
export function loadBundledIds(path = BUNDLED_IDS_FILE): Map<string, string> {
  const f = JSON.parse(readFileSync(path, 'utf8')) as Partial<BundledIdsFile>;
  if (!Array.isArray(f.entries) || f.entries.some((e) => !e || typeof e.id !== 'string' || !PHOTO_ID_RE.test(e.id) || typeof e.name !== 'string' || !e.name.trim())) throw new Error(`${path}：entries 不对`);
  const m = new Map(f.entries.map((e) => [e.id, normalizePhotoName(e.name)]));
  if (m.size !== f.entries.length || f.count !== m.size) throw new Error(`${path}：id 有重复或 count 对不上`);
  return m;
}

function main() {
  const [manifestPath, appCommit] = process.argv.slice(2);
  if (!manifestPath || !appCommit) { console.error('用法：node pipeline/officials/bundled-ids.ts <app 的 photos-manifest.json> <app 提交 hash>'); process.exit(2); }
  process.stdout.write(JSON.stringify(bundledIdsFrom(JSON.parse(readFileSync(manifestPath, 'utf8')), appCommit), null, 1) + '\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try { main(); } catch (e) { console.error(`失败：${e instanceof Error ? e.message : e}`); process.exit(2); }
}
